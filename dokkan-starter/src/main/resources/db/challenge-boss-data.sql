-- 活动挑战副本数据；部署前备份数据库，本脚本只新增表。
CREATE TABLE IF NOT EXISTS `challenge_event` (
  `id` varchar(36) NOT NULL COMMENT '本地主键UUID',
  `region` varchar(16) NOT NULL COMMENT '源地区',
  `language` varchar(16) NOT NULL COMMENT '源语言',
  `event_id` bigint NOT NULL COMMENT '源活动ID',
  `event_name` varchar(255) DEFAULT NULL COMMENT '活动名称',
  `group_id` int NOT NULL COMMENT '源活动分组，仅挑战组5',
  `source_present` tinyint(1) NOT NULL DEFAULT 1 COMMENT '最近完整目录是否包含此活动',
  `category_id` int DEFAULT NULL COMMENT '源活动分类',
  `stage_count` int DEFAULT NULL COMMENT '逻辑关卡数',
  `captured_stages` int DEFAULT NULL COMMENT '源声明已采集关卡数',
  `release_time` datetime DEFAULT NULL COMMENT '活动开放时间UTC',
  `latest_stage_time` datetime DEFAULT NULL COMMENT '最新关卡开放时间UTC',
  `order_by_time` datetime DEFAULT NULL COMMENT '列表排序时间UTC',
  `release_date_status` varchar(32) DEFAULT NULL COMMENT '源时间可信状态',
  `source_updated_text` varchar(128) DEFAULT NULL COMMENT '源更新时间原文',
  `banner_list` varchar(1024) DEFAULT NULL COMMENT '列表图片URL',
  `banner_top` varchar(1024) DEFAULT NULL COMMENT '顶部图片URL',
  `source_hash` char(64) DEFAULT NULL COMMENT '活动目录详情内容hash',
  `synced_time` datetime DEFAULT NULL COMMENT '活动目录最近成功同步时间UTC',
  `source_payload` json DEFAULT NULL COMMENT '活动未知扩展字段JSON',
  `creator` varchar(128) DEFAULT NULL COMMENT '创建人',
  `create_time` datetime NOT NULL DEFAULT CURRENT_TIMESTAMP COMMENT '创建时间',
  `modifier` varchar(128) DEFAULT NULL COMMENT '修改人',
  `update_time` datetime NOT NULL DEFAULT CURRENT_TIMESTAMP ON UPDATE CURRENT_TIMESTAMP COMMENT '修改时间',
  PRIMARY KEY (`id`),
  UNIQUE KEY `uk_event_scope` (`region`,`language`,`event_id`),
  KEY `idx_event_scope_time` (`region`,`language`,`order_by_time`,`event_id`)
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4 COMMENT='活动挑战目录';

CREATE TABLE IF NOT EXISTS `challenge_stage` (
  `id` varchar(36) NOT NULL COMMENT '本地主键UUID',
  `event_record_id` varchar(36) NOT NULL COMMENT '活动本地ID',
  `region` varchar(16) NOT NULL COMMENT '源地区',
  `language` varchar(16) NOT NULL COMMENT '源语言',
  `stage_id` bigint NOT NULL COMMENT '源逻辑关卡ID',
  `stage_name` varchar(255) DEFAULT NULL COMMENT '关卡名称',
  `display_order` int NOT NULL COMMENT '源数组顺序，从0开始',
  `source_present` tinyint(1) NOT NULL DEFAULT 1 COMMENT '最近完整详情是否包含此关卡',
  `release_time` datetime DEFAULT NULL COMMENT '关卡开放时间UTC',
  `release_date_status` varchar(32) DEFAULT NULL COMMENT '源时间可信状态',
  `attributes` json DEFAULT NULL COMMENT 'start_at原文及扩展字段',
  `creator` varchar(128) DEFAULT NULL COMMENT '创建人',
  `create_time` datetime NOT NULL DEFAULT CURRENT_TIMESTAMP COMMENT '创建时间',
  `modifier` varchar(128) DEFAULT NULL COMMENT '修改人',
  `update_time` datetime NOT NULL DEFAULT CURRENT_TIMESTAMP ON UPDATE CURRENT_TIMESTAMP COMMENT '修改时间',
  PRIMARY KEY (`id`),
  UNIQUE KEY `uk_stage_scope` (`region`,`language`,`stage_id`),
  KEY `idx_stage_event_order` (`event_record_id`,`display_order`)
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4 COMMENT='活动挑战逻辑关卡';

CREATE TABLE IF NOT EXISTS `challenge_map` (
  `id` varchar(36) NOT NULL COMMENT '本地主键UUID',
  `stage_record_id` varchar(36) NOT NULL COMMENT '关卡本地ID',
  `region` varchar(16) NOT NULL COMMENT '源地区',
  `language` varchar(16) NOT NULL COMMENT '源语言',
  `map_id` bigint NOT NULL COMMENT '源难度地图ID',
  `difficulty` int DEFAULT NULL COMMENT '源难度编码',
  `difficulty_name` varchar(64) DEFAULT NULL COMMENT '源难度名称',
  `act` int DEFAULT NULL COMMENT '体力消耗',
  `display_order` int NOT NULL COMMENT '源数组顺序，从0开始',
  `source_present` tinyint(1) NOT NULL DEFAULT 1 COMMENT '最近完整详情是否包含此难度',
  `release_time` datetime DEFAULT NULL COMMENT '开放时间UTC',
  `release_date_status` varchar(32) DEFAULT NULL COMMENT '源时间可信状态',
  `enemy_data_flag` tinyint(1) DEFAULT NULL COMMENT '目录声明是否存在敌人数据',
  `capture_status` varchar(32) DEFAULT NULL COMMENT '最近源采集状态',
  `source_available` tinyint(1) DEFAULT NULL COMMENT '最近源响应available值',
  `source_partial` tinyint(1) DEFAULT NULL COMMENT '最近源响应partial值',
  `data_status` varchar(16) NOT NULL DEFAULT 'none' COMMENT '本地快照none、partial或captured',
  `last_sync_status` varchar(16) NOT NULL DEFAULT 'never' COMMENT '最近同步never、success或failed',
  `phase_grouping_confirmed` tinyint(1) DEFAULT NULL COMMENT '有效快照阶段分组是否确认',
  `display_type` varchar(32) DEFAULT NULL COMMENT '源展示类型及分支提示',
  `source_hash` char(64) DEFAULT NULL COMMENT '有效战斗快照hash',
  `source_payload` json DEFAULT NULL COMMENT '地图未知扩展字段JSON',
  `last_observation` json DEFAULT NULL COMMENT '最近源观察结果JSON',
  `last_checked_at` datetime DEFAULT NULL COMMENT '最近请求时间UTC',
  `synced_time` datetime DEFAULT NULL COMMENT '有效快照保存时间UTC',
  `last_error` text COMMENT '最近错误摘要',
  `creator` varchar(128) DEFAULT NULL COMMENT '创建人',
  `create_time` datetime NOT NULL DEFAULT CURRENT_TIMESTAMP COMMENT '创建时间',
  `modifier` varchar(128) DEFAULT NULL COMMENT '修改人',
  `update_time` datetime NOT NULL DEFAULT CURRENT_TIMESTAMP ON UPDATE CURRENT_TIMESTAMP COMMENT '修改时间',
  PRIMARY KEY (`id`),
  UNIQUE KEY `uk_map_scope` (`region`,`language`,`map_id`),
  KEY `idx_map_stage_order` (`stage_record_id`,`display_order`),
  KEY `idx_map_scope_status` (`region`,`language`,`data_status`)
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4 COMMENT='活动挑战难度地图及Boss快照状态';

CREATE TABLE IF NOT EXISTS `challenge_battle` (
  `id` varchar(36) NOT NULL COMMENT '本地主键UUID',
  `map_record_id` varchar(36) NOT NULL COMMENT '难度地图本地ID',
  `battle_index` int NOT NULL COMMENT '源数组位置，从0开始',
  `battle_number` int DEFAULT NULL COMMENT '源展示编号',
  `space` varchar(64) DEFAULT NULL COMMENT '地图位置原文',
  `boss_flag` tinyint(1) DEFAULT NULL COMMENT '源Boss标记',
  `attributes` json DEFAULT NULL COMMENT '战斗扩展字段JSON',
  `creator` varchar(128) DEFAULT NULL COMMENT '创建人',
  `create_time` datetime NOT NULL DEFAULT CURRENT_TIMESTAMP COMMENT '创建时间',
  `modifier` varchar(128) DEFAULT NULL COMMENT '修改人',
  `update_time` datetime NOT NULL DEFAULT CURRENT_TIMESTAMP ON UPDATE CURRENT_TIMESTAMP COMMENT '修改时间',
  PRIMARY KEY (`id`),
  UNIQUE KEY `uk_battle_position` (`map_record_id`,`battle_index`)
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4 COMMENT='挑战副本战斗';

CREATE TABLE IF NOT EXISTS `challenge_phase` (
  `id` varchar(36) NOT NULL COMMENT '本地主键UUID',
  `battle_record_id` varchar(36) NOT NULL COMMENT '战斗本地ID',
  `phase_index` int NOT NULL COMMENT '源round数组位置，从0开始',
  `phase_number` int DEFAULT NULL COMMENT '源阶段展示编号',
  `comment` text COMMENT '源阶段备注',
  `attributes` json DEFAULT NULL COMMENT '阶段分支及扩展字段JSON',
  `creator` varchar(128) DEFAULT NULL COMMENT '创建人',
  `create_time` datetime NOT NULL DEFAULT CURRENT_TIMESTAMP COMMENT '创建时间',
  `modifier` varchar(128) DEFAULT NULL COMMENT '修改人',
  `update_time` datetime NOT NULL DEFAULT CURRENT_TIMESTAMP ON UPDATE CURRENT_TIMESTAMP COMMENT '修改时间',
  PRIMARY KEY (`id`),
  UNIQUE KEY `uk_phase_position` (`battle_record_id`,`phase_index`)
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4 COMMENT='挑战副本阶段';

CREATE TABLE IF NOT EXISTS `challenge_enemy` (
  `id` varchar(36) NOT NULL COMMENT '本地主键UUID',
  `phase_record_id` varchar(36) NOT NULL COMMENT '阶段本地ID',
  `enemy_index` int NOT NULL COMMENT '源数组位置，从0开始',
  `enemy_id` bigint DEFAULT NULL COMMENT '源敌人定义ID，可重复出场',
  `enemy_name` varchar(255) DEFAULT NULL COMMENT '敌人名称',
  `rarity` int DEFAULT NULL COMMENT '源稀有度',
  `element` int DEFAULT NULL COMMENT '源属性编码',
  `resource_id` bigint DEFAULT NULL COMMENT '源头像资源ID，不是玩家卡片ID',
  `thumbnail` varchar(1024) DEFAULT NULL COMMENT '敌人缩略图URL',
  `hp_value` bigint DEFAULT NULL COMMENT '基础HP，未知为NULL',
  `atk_value` bigint DEFAULT NULL COMMENT '基础ATK，未知为NULL',
  `def_value` bigint DEFAULT NULL COMMENT '基础DEF，未知为NULL',
  `damage_reduction` decimal(10,4) DEFAULT NULL COMMENT '源DR百分数',
  `conditional_dr` tinyint(1) DEFAULT NULL COMMENT '是否条件减伤',
  `max_attacks` int DEFAULT NULL COMMENT '源最大攻击次数',
  `base_sa_weight_share` decimal(10,4) DEFAULT NULL COMMENT '基础必杀权重占比',
  `super_only_finish` tinyint(1) DEFAULT NULL COMMENT '是否只能被必杀终结',
  `required_flag` tinyint(1) DEFAULT NULL COMMENT '源required标记',
  `available_flag` tinyint(1) DEFAULT NULL COMMENT '源敌人数据可用标记',
  `skill_definitions` json DEFAULT NULL COMMENT '完整敌人技能定义JSON',
  `round_skill` json DEFAULT NULL COMMENT '敌人阶段技能JSON',
  `super_attacks` json DEFAULT NULL COMMENT '敌人必杀攻击JSON',
  `ai_rules` json DEFAULT NULL COMMENT '敌人AI规则JSON',
  `attributes` json DEFAULT NULL COMMENT '其他源字段JSON',
  `creator` varchar(128) DEFAULT NULL COMMENT '创建人',
  `create_time` datetime NOT NULL DEFAULT CURRENT_TIMESTAMP COMMENT '创建时间',
  `modifier` varchar(128) DEFAULT NULL COMMENT '修改人',
  `update_time` datetime NOT NULL DEFAULT CURRENT_TIMESTAMP ON UPDATE CURRENT_TIMESTAMP COMMENT '修改时间',
  PRIMARY KEY (`id`),
  UNIQUE KEY `uk_enemy_position` (`phase_record_id`,`enemy_index`),
  KEY `idx_enemy_id` (`enemy_id`)
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4 COMMENT='挑战副本敌人出场';
